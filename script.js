/* =========================================================
   ESCAPE REGEX
========================================================= */

function escapeRegExp(
    text
) {

    return text.replace(
        /[.*+?^${}()|[\]\\]/g,
        "\\$&"
    );

}


/* =========================================================
   REPLACE FORMAL WORDS
========================================================= */

function replaceFormalWords(
    text
) {

    const replacements =
        Object.entries(
            naturalReplacements
        ).sort(
            (a, b) =>
                b[0].length -
                a[0].length
        );


    for (
        const [formal, natural]
        of replacements
    ) {

        const regex =
            new RegExp(
                `\\b${escapeRegExp(formal)}\\b`,
                "gi"
            );


        text =
            text.replace(
                regex,
                function(match) {

                    /*
                       Preserve the first-letter
                       capitalization.
                    */

                    if (
                        match[0] ===
                        match[0].toUpperCase()
                    ) {

                        return (
                            natural
                                .charAt(0)
                                .toUpperCase()
                            +
                            natural.slice(1)
                        );

                    }


                    return natural;

                }
            );

    }


    return text;

}


/* =========================================================
   CLEAN SPACING
========================================================= */

function cleanSpacing(
    text
) {

    return text

        .replace(
            /[ \t]+/g,
            " "
        )

        .replace(
            / +([,.!?;:])/g,
            "$1"
        )

        .replace(
            /([,.!?;:])([A-Za-z])/g,
            "$1 $2"
        )

        .replace(
            /\n{3,}/g,
            "\n\n"
        )

        .trim();

}


/* =========================================================
   IMPROVE TRANSITIONS
========================================================= */

function improveTransitions(
    text
) {

    const replacements = [

        {
            from:
                /^Furthermore,\s*/i,

            to:
                "Also, "
        },

        {
            from:
                /^Moreover,\s*/i,

            to:
                "Also, "
        },

        {
            from:
                /^In conclusion,\s*/i,

            to:
                "Overall, "
        },

        {
            from:
                /^In summary,\s*/i,

            to:
                "Overall, "
        },

        {
            from:
                /^It is important to note that\s*/i,

            to:
                ""
        },

        {
            from:
                /^It is worth noting that\s*/i,

            to:
                ""
        },

        {
            from:
                /^It should be noted that\s*/i,

            to:
                ""
        }

    ];


    const sentences =
        text.split(
            /(?<=[.!?])\s+/
        );


    return sentences
        .map(
            sentence => {

                for (
                    const replacement
                    of replacements
                ) {

                    sentence =
                        sentence.replace(
                            replacement.from,
                            replacement.to
                        );

                }


                return sentence;

            }
        )
        .join(" ");

}


/* =========================================================
   VARY REPEATED SENTENCE STARTS
========================================================= */

function varySentenceStarts(
    text
) {

    const sentences =
        text.split(
            /(?<=[.!?])\s+/
        );


    let previousStart =
        "";


    const alternatives = {

        "This": [

            "The idea",

            "This approach",

            "The concept"

        ],


        "These": [

            "Such",

            "Those",

            "These ideas"

        ],


        "The": [

            "This",

            "Another",

            "One"

        ]

    };


    return sentences

        .map(
            sentence => {

                const words =
                    sentence
                        .trim()
                        .split(/\s+/);


                if (
                    words.length < 5
                ) {

                    return sentence;

                }


                const start =
                    words[0];


                if (
                    start === previousStart &&
                    alternatives[start]
                ) {

                    const choices =
                        alternatives[
                            start
                        ];


                    const replacement =
                        choices[
                            Math.floor(
                                Math.random() *
                                choices.length
                            )
                        ];


                    words[0] =
                        replacement;


                    sentence =
                        words.join(
                            " "
                        );

                }


                previousStart =
                    start;


                return sentence;

            }
        )

        .join(" ");

}


/* =========================================================
   IMPROVE VERY LONG SENTENCES
========================================================= */

function improveLongSentences(
    text
) {

    const sentences =
        text.split(
            /(?<=[.!?])\s+/
        );


    return sentences

        .map(
            sentence => {

                const words =
                    sentence.split(
                        /\s+/
                    );


                /*
                   Only modify extremely long
                   sentences.
                */

                if (
                    words.length <= 45
                ) {

                    return sentence;

                }


                const commaIndex =
                    sentence.indexOf(
                        ","
                    );


                if (
                    commaIndex > 20 &&
                    commaIndex <
                    sentence.length - 20
                ) {

                    const first =
                        sentence.slice(
                            0,
                            commaIndex
                        );


                    const second =
                        sentence
                            .slice(
                                commaIndex + 1
                            )
                            .trim();


                    return (

                        first +

                        ". " +

                        second
                            .charAt(0)
                            .toUpperCase() +

                        second.slice(1)

                    );

                }


                return sentence;

            }
        )

        .join(" ");

}


/* =========================================================
   HUMANIZE TEXT
========================================================= */

function humanizeText(
    text
) {

    let result =
        text;


    /*
       STEP 1
       Clean spaces.
    */

    result =
        cleanSpacing(
            result
        );


    /*
       STEP 2
       Replace unnecessarily formal
       wording.
    */

    result =
        replaceFormalWords(
            result
        );


    /*
       STEP 3
       Improve transitions.
    */

    result =
        improveTransitions(
            result
        );


    /*
       STEP 4
       Reduce repetitive starts.
    */

    result =
        varySentenceStarts(
            result
        );


    /*
       STEP 5
       Handle extremely long sentences.
    */

    result =
        improveLongSentences(
            result
        );


    /*
       STEP 6
       Final cleanup.
    */

    result =
        cleanSpacing(
            result
        );


    return result;

}


