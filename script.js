/* =========================================================
   WORD COUNT
========================================================= */

function countWords(text) {

    if (!text.trim()) {

        return 0;

    }


    /*
       Unicode-aware word matching.

       Supports English and many other
       Unicode writing systems.
    */

    const matches =
        text.match(
            /[\p{L}\p{N}]+(?:['’-][\p{L}\p{N}]+)*/gu
        );


    return matches
        ? matches.length
        : 0;

}


/* =========================================================
   TOKENIZE TEXT
========================================================= */

function tokenize(text) {

    const matches =
        text
            .toLowerCase()
            .match(
                /[\p{L}\p{N}]+(?:['’-][\p{L}\p{N}]+)*/gu
            );


    return matches || [];

}


/* =========================================================
   GET SENTENCES
========================================================= */

function getSentences(text) {

    return text
        .split(/[.!?]+/)
        .map(
            sentence =>
                sentence.trim()
        )
        .filter(
            sentence =>
                sentence.length > 0
        );

}


/* =========================================================
   AVERAGE
========================================================= */

function average(numbers) {

    if (
        numbers.length === 0
    ) {

        return 0;

    }


    return (
        numbers.reduce(
            (sum, value) =>
                sum + value,
            0
        )
        /
        numbers.length
    );

}


/* =========================================================
   STANDARD DEVIATION
========================================================= */

function standardDeviation(numbers) {

    if (
        numbers.length === 0
    ) {

        return 0;

    }


    const avg =
        average(numbers);


    const variance =
        average(
            numbers.map(
                number =>
                    Math.pow(
                        number - avg,
                        2
                    )
            )
        );


    return Math.sqrt(
        variance
    );

}


/* =========================================================
   SENTENCE LENGTHS
========================================================= */

function getSentenceLengths(
    sentences
) {

    return sentences.map(
        sentence =>
            countWords(sentence)
    );

}


/* =========================================================
   VOCABULARY RATIO
========================================================= */

function vocabularyRatio(
    tokens
) {

    if (
        tokens.length === 0
    ) {

        return 0;

    }


    const uniqueWords =
        new Set(tokens);


    return (
        uniqueWords.size /
        tokens.length
    );

}


/* =========================================================
   REPETITION RATIO
========================================================= */

function repetitionRatio(
    tokens
) {

    if (
        tokens.length === 0
    ) {

        return 0;

    }


    const frequencies =
        new Map();


    for (
        const word of tokens
    ) {

        frequencies.set(
            word,
            (
                frequencies.get(
                    word
                ) || 0
            ) + 1
        );

    }


    let repeatedWords = 0;


    for (
        const frequency
        of frequencies.values()
    ) {

        if (
            frequency > 1
        ) {

            repeatedWords +=
                frequency - 1;

        }

    }


    return (
        repeatedWords /
        tokens.length
    );

}


/* =========================================================
   AI PHRASE DETECTION
========================================================= */

function findAIPhrases(text) {

    const lowerText =
        text.toLowerCase();


    let hits = 0;


    const found = [];


    for (
        const phrase
        of AI_PHRASES
    ) {

        let position = 0;

        let phraseCount = 0;


        while (true) {

            const index =
                lowerText.indexOf(
                    phrase,
                    position
                );


            if (
                index === -1
            ) {

                break;

            }


            phraseCount++;


            position =
                index +
                phrase.length;

        }


        if (
            phraseCount > 0
        ) {

            hits +=
                phraseCount;


            found.push({

                phrase:
                    phrase,

                count:
                    phraseCount

            });

        }

    }


    return {

        hits:
            hits,

        found:
            found

    };

}


/* =========================================================
   FIRST-PERSON COUNT
========================================================= */

function firstPersonCount(text) {

    const matches =
        text
            .toLowerCase()
            .match(
                /\b(i|i'm|i’ve|i'd|my|me|we|our|us)\b/g
            );


    return matches
        ? matches.length
        : 0;

}


/* =========================================================
   CONTRACTION COUNT
========================================================= */

function contractionCount(text) {

    const matches =
        text.match(
            /\b[\p{L}]+(?:['’][\p{L}]+)\b/gu
        );


    return matches
        ? matches.length
        : 0;

}


/* =========================================================
   PUNCTUATION COUNT
========================================================= */

function punctuationCount(text) {

    const matches =
        text.match(
            /[,;:—–-]/g
        );


    return matches
        ? matches.length
        : 0;

}


/* =========================================================
   PARAGRAPH COUNT
========================================================= */

function paragraphCount(text) {

    const paragraphs =
        text
            .split(
                /\n\s*\n/
            )
            .filter(
                paragraph =>
                    paragraph.trim()
                        .length > 0
            );


    /*
       If there is text but no blank line,
       count it as one paragraph.
    */

    if (
        paragraphs.length === 0 &&
        text.trim().length > 0
    ) {

        return 1;

    }


    return paragraphs.length;

}


/* =========================================================
   FEATURE EXTRACTION
========================================================= */

function extractFeatures(text) {

    const tokens =
        tokenize(text);


    const sentences =
        getSentences(text);


    const lengths =
        getSentenceLengths(
            sentences
        );


    const avgSentenceLength =
        average(lengths);


    const deviation =
        standardDeviation(
            lengths
        );


    /*
       Sentence-length variation.

       This is only one weak signal.
    */

    const burstiness =
        avgSentenceLength > 0

            ? deviation /
              avgSentenceLength

            : 0;


    const vocabulary =
        vocabularyRatio(
            tokens
        );


    const repetition =
        repetitionRatio(
            tokens
        );


    const aiPhrases =
        findAIPhrases(
            text
        );


    const firstPerson =
        firstPersonCount(
            text
        );


    const contractions =
        contractionCount(
            text
        );


    const punctuation =
        punctuationCount(
            text
        );


    return {

        wordCount:
            tokens.length,

        characterCount:
            text.length,

        sentenceCount:
            sentences.length,

        paragraphCount:
            paragraphCount(
                text
            ),

        averageSentenceLength:
            avgSentenceLength,

        burstiness:
            burstiness,

        vocabularyRatio:
            vocabulary,

        repetitionRatio:
            repetition,

        aiPhraseHits:
            aiPhrases.hits,

        firstPersonCount:
            firstPerson,

        contractionCount:
            contractions,

        punctuationCount:
            punctuation

    };

}


/* =========================================================
   DETECTION ALGORITHM
========================================================= */

function detectText(text) {

    const features =
        extractFeatures(
            text
        );


    /*
       Start at neutral.
    */

    let score = 50;


    /* -----------------------------------------
       SENTENCE VARIATION
    ----------------------------------------- */

    if (
        features.burstiness <
        0.35
    ) {

        score += 12;

    }

    else if (
        features.burstiness >
        0.85
    ) {

        score -= 10;

    }


    /* -----------------------------------------
       VOCABULARY
    ----------------------------------------- */

    if (
        features.vocabularyRatio >
        0.72
    ) {

        score += 5;

    }

    else if (
        features.vocabularyRatio <
        0.50
    ) {

        score -= 4;

    }


    /* -----------------------------------------
       AI-STYLE PHRASES
    ----------------------------------------- */

    score += Math.min(
        features.aiPhraseHits * 2.5,
        15
    );


    /* -----------------------------------------
       REPETITION
    ----------------------------------------- */

    score += Math.min(
        features.repetitionRatio * 20,
        8
    );


    /* -----------------------------------------
       FIRST PERSON
    ----------------------------------------- */

    const firstPersonRatio =
        features.wordCount > 0

            ? features.firstPersonCount /
              features.wordCount

            : 0;


    score -= Math.min(
        firstPersonRatio * 80,
        10
    );


    /* -----------------------------------------
       CONTRACTIONS
    ----------------------------------------- */

    const contractionRatio =
        features.wordCount > 0

            ? features.contractionCount /
              features.wordCount

            : 0;


    score -= Math.min(
        contractionRatio * 100,
        8
    );


    /* -----------------------------------------
       LIMIT RESULT
    ----------------------------------------- */

    score =
        Math.max(
            1,
            Math.min(
                99,
                Math.round(score)
            )
        );


    /* -----------------------------------------
       RESULT LABEL
    ----------------------------------------- */

    let label;

    let confidence;


    if (
        score >= 65
    ) {

        label =
            "Likely AI-assisted";


        confidence =
            score;

    }

    else if (
        score <= 35
    ) {

        label =
            "Likely human-written";


        confidence =
            100 - score;

    }

    else {

        label =
            "Uncertain / mixed";


        confidence =
            50 +
            Math.abs(
                score - 50
            );

    }


    return {

        aiProbability:
            score,

        humanProbability:
            100 - score,

        label:
            label,

        confidence:
            Math.round(
                confidence
            ),

        features:
            features

    };

}


